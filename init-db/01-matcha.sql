CREATE VIEW users_me_like AS
SELECT m.user1_id AS me, uwi.*
FROM matches m
JOIN users_with_interests uwi ON uwi.id = m.user2_id
WHERE m.status = 'like';

CREATE VIEW users_who_like_me AS
SELECT m.user2_id AS me, uwi.*
FROM matches m
JOIN users_with_interests uwi ON uwi.id = m.user1_id
WHERE m.status = 'like';

CREATE OR REPLACE FUNCTION compatible_users_from(
  ref_user_id UUID
)
RETURNS TABLE (
  id UUID,
  first_name TEXT,
  last_name TEXT,
  gender TEXT,
  city TEXT,
  bio TEXT,
  age INT,
  interests JSON,
  fame INT,
  distance INT
)
AS $$
  SELECT
    u.id,
    u.first_name,
    u.last_name,
    u.gender,
    u.city,
    u.bio,
    u.age,
    u.interests,
    u.fame,
    ceil(
      earth_distance(
        ll_to_earth(me.latitude, me.longitude),
        ll_to_earth(u.latitude, u.longitude)
      ) / 1000
    )::int AS distance
  FROM users_with_interests u
  JOIN users me ON me.id = ref_user_id
  WHERE
    u.id <> me.id
    AND (
      me.sex_pref = 'B' OR me.sex_pref = u.gender
    )
    AND (
      u.sex_pref = 'B' OR u.sex_pref = me.gender
    )
    AND NOT EXISTS (
      SELECT 1
      FROM matches m
      WHERE
        (
          (m.user1_id = ref_user_id AND m.user2_id = u.id)
          OR
          (m.user1_id = u.id AND m.user2_id = ref_user_id)
        )
        AND m.status = 'block'
    );
$$ LANGUAGE sql STABLE;






