  "reported_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "created_at" timestamptz DEFAULT (current_timestamp),
  UNIQUE ("reporter_id", "reported_id"),
  CHECK ("reporter_id" <> "reported_id")
);

