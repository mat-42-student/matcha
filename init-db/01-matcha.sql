CREATE TABLE "users" (
  "id" uuid PRIMARY KEY DEFAULT (gen_random_uuid()),

  "username" varchar(20) NOT NULL
    CHECK (username ~ $$^[A-Za-z0-9_]{3,20}$$),

  "first_name" varchar(50) NOT NULL
    CHECK (char_length(first_name) >= 2 AND first_name !~ $$[^A-Za-zÀ-ÖØ-öø-ÿ' -]$$),

  "last_name" varchar(50) NOT NULL
    CHECK (char_length(last_name) >= 2 AND last_name !~ $$[^A-Za-zÀ-ÖØ-öø-ÿ' -]$$),

  "email" varchar(255) UNIQUE NOT NULL
    CHECK (email ~ $$^[^@\s]+@[^@\s]+\.[^@\s]+$$),

  "passwd" varchar(255) NOT NULL,

  "birthdate" date NOT NULL
    CHECK (
      birthdate <= (current_date - interval '18 years') AND
      birthdate >= (current_date - interval '100 years')
    ),    

  "country" varchar(30)
    CHECK (country IS NULL OR country !~ $$[^A-Za-zÀ-ÖØ-öø-ÿ' -]$$),

  "city" varchar(50)
    CHECK (city IS NULL OR city !~ $$[^A-Za-zÀ-ÖØ-öø-ÿ' -]$$),

  "latitude" float CHECK (latitude BETWEEN -90 AND 90),
  "longitude" float CHECK (longitude BETWEEN -180 AND 180),

  "gender" char(1) CHECK (gender IN ('M', 'F')),
  -- unspecified orientation = bisexual (subject IV.3)
  "sex_pref" char(1) NOT NULL DEFAULT 'B' CHECK (sex_pref IN ('M', 'F', 'B')),

  "bio" text,
  -- starting popularity given by the seed (0 for real accounts); the fame itself is user_fame()
  "base_fame" int NOT NULL DEFAULT 0 CHECK (base_fame BETWEEN 0 AND 100),
  -- distinct users who reported this account as fake (see reports)
  "report_count" int NOT NULL DEFAULT 0 CHECK (report_count >= 0),

  "is_verified" boolean DEFAULT false,
  
  "last_login" timestamptz DEFAULT (current_timestamp),

  "created_at" timestamptz DEFAULT (current_timestamp)
);

-- Emails are stored in lower case by the app: "A@x.com" and "a@x.com" are the same account
CREATE UNIQUE INDEX "users_email_lower_idx" ON "users" (lower("email"));

CREATE TABLE pictures (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL,
  "mime_type" varchar(10),
  "data" bytea NULL,
  "is_main" boolean DEFAULT false
);

-- Fonction that prevent to addd more that 5 pic
CREATE OR REPLACE FUNCTION check_max_pictures()
RETURNS trigger AS $$
BEGIN
  IF (SELECT COUNT(*) FROM pictures WHERE user_id = NEW.user_id) >= 5 THEN
    RAISE EXCEPTION 'Limite de 5 photos atteinte pour cet utilisateur';
  END IF;
  RETURN NEW;
END;
$$ LANGUAGE plpgsql;

-- trigger that call check_max_pictures at every insertion
CREATE TRIGGER pictures_limit_trigger
BEFORE INSERT ON pictures
FOR EACH ROW
EXECUTE FUNCTION check_max_pictures();

