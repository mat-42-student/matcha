-- One row per direction: (A, B) and (B, A) for a match between A and B
CREATE VIEW user_matches AS
SELECT
  l.liker_id AS user_id,
  l.liked_id AS matched_id,
  GREATEST(l.created_at, r.created_at) AS created_at
FROM likes l
JOIN likes r ON r.liker_id = l.liked_id AND r.liked_id = l.liker_id;

-- Either user blocked the other
CREATE OR REPLACE FUNCTION is_blocked(user_a UUID, user_b UUID)
RETURNS boolean
AS $$
  SELECT EXISTS (
    SELECT 1 FROM blocks
    WHERE (blocker_id = user_a AND blocked_id = user_b)
       OR (blocker_id = user_b AND blocked_id = user_a)
  );
$$ LANGUAGE sql STABLE;

-- Relation seen from me_id, values of LikeStatus in lib/types.ts
CREATE OR REPLACE FUNCTION like_status(me_id UUID, other_id UUID)
RETURNS text
AS $$
  SELECT CASE
    WHEN is_blocked(me_id, other_id) THEN 'block'
    WHEN i_like AND likes_me THEN 'match'
    WHEN i_like THEN 'like'
    WHEN likes_me THEN 'isLiked'
    ELSE 'none'
  END
  FROM (
    SELECT
      EXISTS (SELECT 1 FROM likes WHERE liker_id = me_id AND liked_id = other_id) AS i_like,
      EXISTS (SELECT 1 FROM likes WHERE liker_id = other_id AND liked_id = me_id) AS likes_me
  ) AS l;
$$ LANGUAGE sql STABLE;

-- Distance in km between two users (earthdistance), NULL if either has no location
CREATE OR REPLACE FUNCTION distance_km(user_a UUID, user_b UUID)
RETURNS int
AS $$
  SELECT round(earth_distance(
    ll_to_earth(a.latitude, a.longitude),
    ll_to_earth(b.latitude, b.longitude)
  ) / 1000)::int
  FROM users a, users b
  WHERE a.id = user_a AND b.id = user_b;
$$ LANGUAGE sql STABLE;

-- Pending likes only: a reciprocated like is listed in user_matches
CREATE VIEW users_me_like AS
SELECT l.liker_id AS me, uwi.*
FROM likes l
JOIN users_with_interests uwi ON uwi.id = l.liked_id
WHERE NOT EXISTS (
  SELECT 1 FROM likes r WHERE r.liker_id = l.liked_id AND r.liked_id = l.liker_id
);

CREATE VIEW users_who_like_me AS
SELECT l.liked_id AS me, uwi.*
FROM likes l
JOIN users_with_interests uwi ON uwi.id = l.liker_id
WHERE NOT EXISTS (
  SELECT 1 FROM likes r WHERE r.liker_id = l.liked_id AND r.liked_id = l.liker_id
);

-- Accounts reported as fake by report_threshold distinct users are hidden
CREATE OR REPLACE FUNCTION compatible_users_from(
  ref_user_id UUID,
  report_threshold INT DEFAULT 2
)
RETURNS TABLE (
  id UUID,
  username TEXT,
  first_name TEXT,
  last_name TEXT,
  gender TEXT,
  sex_pref TEXT,
  city TEXT,
  bio TEXT,
  age INT,
  interests JSON,
  fame INT,
  distance INT,
  "likeStatus" TEXT
)
AS $$
  SELECT
    u.id,
    u.username,
    u.first_name,
    u.last_name,
    u.gender,
    u.sex_pref,
    u.city,
    u.bio,
    u.age,
    u.interests,
    u.fame,
    distance_km(ref_user_id, u.id),
    like_status(ref_user_id, u.id)
  FROM users_with_interests u
  JOIN users me ON me.id = ref_user_id
  JOIN users target ON target.id = u.id
  WHERE
    u.id <> me.id
    AND target.report_count < report_threshold
    -- only complete profiles (keep in sync with lib/profileCompletion.ts)
    AND u.gender IS NOT NULL
    AND target.latitude IS NOT NULL
    AND target.longitude IS NOT NULL
    AND json_array_length(u.interests) >= 3
    AND EXISTS (
      SELECT 1 FROM pictures p WHERE p.user_id = u.id AND p.is_main
    )
    AND (
      me.sex_pref = 'B' OR me.sex_pref = u.gender
    )
    AND (
      u.sex_pref = 'B' OR u.sex_pref = me.gender
    )
    AND NOT is_blocked(ref_user_id, u.id);
$$ LANGUAGE sql STABLE;

