CREATE TABLE "email_verifications" (
  "id" uuid PRIMARY KEY DEFAULT (gen_random_uuid()),
  "user_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "token" varchar(255) UNIQUE NOT NULL,
  "expires_at" timestamp DEFAULT (current_timestamp + interval '1 days'),
  "created_at" timestamp DEFAULT (current_timestamp)
);

CREATE VIEW "users_with_interests" AS
SELECT
  u.id,
  u.first_name,
  LEFT(u.last_name, 1) AS last_name,
  u.gender,
  u.city,
  u.latitude,
  u.longitude,
  u.bio,
  u.fame,
  u.sex_pref,
  date_part('year', age(current_date, u.birthdate))::int AS age,
  COALESCE(json_agg(i.name) FILTER (WHERE i.name IS NOT NULL), '[]') AS interests
FROM users u
LEFT JOIN user_interests ui ON u.id = ui.user_id
LEFT JOIN interests i ON ui.interest_id = i.id
GROUP BY u.id;

