-- A match is two reciprocal likes (see user_matches)
CREATE TABLE "likes" (
  "liker_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "liked_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "created_at" timestamptz DEFAULT (current_timestamp),
  PRIMARY KEY ("liker_id", "liked_id"),
  CHECK ("liker_id" <> "liked_id")
);

CREATE TABLE "blocks" (
  "blocker_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "blocked_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "created_at" timestamptz DEFAULT (current_timestamp),
  PRIMARY KEY ("blocker_id", "blocked_id"),
  CHECK ("blocker_id" <> "blocked_id")
);

-- user_id removed their like (or match) towards unliked_id: unliked_id no longer notifies user_id,
-- until user_id likes them again
CREATE TABLE "unlikes" (
  "user_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "unliked_id" uuid NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  "created_at" timestamptz DEFAULT (current_timestamp),
  PRIMARY KEY ("user_id", "unliked_id"),
  CHECK ("user_id" <> "unliked_id")
);

CREATE TABLE "views" (
  "id" INT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  "user_id" uuid NOT NULL,
